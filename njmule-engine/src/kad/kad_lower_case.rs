/// The network's lower case of one UTF-16 code unit.
pub fn lower_unit(unit: u16) -> u16 {
    match MAP.binary_search_by_key(&unit, |entry| high(*entry)) {
        Ok(at) => MAP.get(at).map_or(unit, |entry| low(*entry)),
        Err(_) => unit,
    }
}

/// `text` in the network's lower case; characters beyond the basic plane, which the table never holds, stay.
pub fn to_lower_case(text: &str) -> String {
    text.chars()
        .map(|c| match u16::try_from(u32::from(c)) {
            Ok(unit) => char::from_u32(u32::from(lower_unit(unit))).unwrap_or(c),
            Err(_) => c,
        })
        .collect()
}

fn high(entry: u32) -> u16 {
    u16::try_from(entry >> 16).unwrap_or_default()
}

fn low(entry: u32) -> u16 {
    u16::try_from(entry & 0xFFFF).unwrap_or_default()
}
