package org.njmule.bench;

import com.google.common.escape.Escaper;
import com.google.common.html.HtmlEscapers;
import java.util.concurrent.TimeUnit;
import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Param;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;

/** Escaping one table cell of the web interface. */
@State(Scope.Thread)
@BenchmarkMode(Mode.AverageTime)
@OutputTimeUnit(TimeUnit.NANOSECONDS)
@Warmup(iterations = 3, time = 1)
@Measurement(iterations = 5, time = 1)
@Fork(1)
public class HtmlEscapeBench {

    private static final Escaper GUAVA = HtmlEscapers.htmlEscaper();

    @Param({"plain", "special"})
    public String kind;

    private String value() {
        return this.kind.equals("plain")
                ? "Ubuntu 24.04.1 LTS Desktop amd64 official release.iso"
                : "Tom & Jerry <Best of> \"1940\" 'remastered' & more.mkv";
    }

    /** The replaced code of the web interface's {@code Html.text}. */
    @Benchmark
    public String handWritten() {
        String value = value();
        StringBuilder out = new StringBuilder(value.length() + 16);
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '&' -> out.append("&amp;");
                case '<' -> out.append("&lt;");
                case '>' -> out.append("&gt;");
                case '"' -> out.append("&quot;");
                case '\'' -> out.append("&#39;");
                default -> out.append(c);
            }
        }
        return out.toString();
    }

    /** Today's code. */
    @Benchmark
    public String guavaHtmlEscaper() {
        return GUAVA.escape(value());
    }
}
