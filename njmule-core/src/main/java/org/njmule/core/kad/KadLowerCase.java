    private static final char[] FROM = new char[MAP.length];
    private static final char[] TO = new char[MAP.length];

    static {
        for (int i = 0; i < MAP.length; i++) {
            FROM[i] = (char) (MAP[i] >>> 16);
            TO[i] = (char) MAP[i];
        }
    }

    private KadLowerCase() {}

    static char toLowerCase(char c) {
        int at = Arrays.binarySearch(FROM, c);
        return at >= 0 ? TO[at] : c;
    }

    static String toLowerCase(String text) {
        char[] chars = text.toCharArray();
        for (int i = 0; i < chars.length; i++) {
            chars[i] = toLowerCase(chars[i]);
        }
        return new String(chars);
    }
