package org.njmule.core.search;

/**
 * The edit distance of two names: insertions, deletions and substitutions of characters. Written here rather than taken
 * from Apache Commons Text, which with commons-lang3 would be two libraries for this one function.
 */
final class Levenshtein {

    private Levenshtein() {}

    /** The fewest single-character edits that turn {@code a} into {@code b}. */
    static int distance(String a, String b) {
        int[] previous = new int[b.length() + 1];
        int[] current = new int[b.length() + 1];
        for (int j = 0; j <= b.length(); j++) {
            previous[j] = j;
        }
        for (int i = 1; i <= a.length(); i++) {
            current[0] = i;
            for (int j = 1; j <= b.length(); j++) {
                int substitution = previous[j - 1] + (a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1);
                current[j] = Math.min(substitution, Math.min(previous[j], current[j - 1]) + 1);
            }
            int[] swap = previous;
            previous = current;
            current = swap;
        }
        return previous[b.length()];
    }
}
