"""Golden vectors for the protocol obfuscation, from a second implementation independent of the
njMule Java code: MD5 key material, RC4 (with the 1024-byte discard for TCP) and the UDP datagram
layout, all with fixed inputs instead of random ones.

Usage: python tools/golden/gen_crypt_vectors.py > njmule-core/src/test/resources/golden/obfuscation.txt
"""

import hashlib
import struct
import sys


def rc4(key):
    s = list(range(256))
    j = 0
    for i in range(256):
        j = (j + s[i] + key[i % len(key)]) & 0xFF
        s[i], s[j] = s[j], s[i]
    i = j = 0
    while True:
        i = (i + 1) & 0xFF
        j = (j + s[i]) & 0xFF
        s[i], s[j] = s[j], s[i]
        yield s[(s[i] + s[j]) & 0xFF]


def crypt(stream, data):
    return bytes(b ^ next(stream) for b in data)


def tcp_stream(material):
    stream = rc4(hashlib.md5(material).digest())
    for _ in range(1024):
        next(stream)
    return stream


def udp_datagram(marker, key_part, sync, material, packet, kad_keys=b""):
    """<marker><key part 2> in clear, then RC4(<sync 4 LE><padding length 0><kad keys><packet>)."""
    stream = rc4(hashlib.md5(material).digest())
    body = struct.pack("<I", sync) + b"\x00" + kad_keys + packet
    return bytes([marker]) + key_part + crypt(stream, body)


def main():
    out = sys.stdout
    user_hash = bytes(range(16))
    out.write("# Generated by tools/golden/gen_crypt_vectors.py\n")

    # TCP client keys: MD5(<receiver user hash 16><magic 34 or 203><random part 4>), discard 1024.
    key_part = bytes([0x01, 0x23, 0x45, 0x67])
    for magic in (34, 203):
        stream = tcp_stream(user_hash + bytes([magic]) + key_part)
        out.write(f"tcp-client magic={magic} keystream={bytes(next(stream) for _ in range(16)).hex()}\n")

    # TCP server keys: MD5(<shared secret 96><magic>), discard 1024.
    secret = bytes((3 * i + 1) & 0xFF for i in range(96))
    for magic in (34, 203):
        stream = tcp_stream(secret + bytes([magic]))
        out.write(f"tcp-server magic={magic} keystream={bytes(next(stream) for _ in range(16)).hex()}\n")

    # UDP eD2K: MD5(<receiver user hash><sender IP><91><random part 2>), sync 0x395F2EC1.
    ip = bytes([192, 168, 1, 10])
    packet = bytes([0xC5, 0x90]) + bytes(range(0xA0, 0xB0))
    key_part = bytes([0x34, 0x12])
    datagram = udp_datagram(0x5B, key_part, 0x395F2EC1, user_hash + ip + bytes([91]) + key_part, packet)
    out.write(f"udp-ed2k packet={packet.hex()} datagram={datagram.hex()}\n")

    # UDP Kad with the receiver's Kad id: MD5(<Kad id 16><random part 2>).
    kad_id = bytes(range(0x10, 0x20))
    packet = bytes([0xE4, 0x11]) + bytes(range(20))
    key_part = bytes([0x78, 0x56])
    keys = struct.pack("<II", 0x11223344, 0x55667788)
    datagram = udp_datagram(0x58, key_part, 0x395F2EC1, kad_id + key_part, packet, keys)
    out.write(f"udp-kad-id packet={packet.hex()} datagram={datagram.hex()}\n")

    # UDP Kad with the receiver's verify key: MD5(<verify key 4 LE><random part 2>).
    datagram = udp_datagram(0x5A, key_part, 0x395F2EC1, struct.pack("<I", 0xCAFEBABE) + key_part,
                            packet, struct.pack("<II", 0xCAFEBABE, 0x55667788))
    out.write(f"udp-kad-verify packet={packet.hex()} datagram={datagram.hex()}\n")

    # UDP to a server: MD5(<server key 4 LE><0x6B><random part 2>), sync 0x13EF24D5.
    packet = bytes([0xE3, 0x96, 0x01, 0x00, 0xAA, 0x55])
    key_part = bytes([0x9A, 0xBC])
    datagram = udp_datagram(0x42, key_part, 0x13EF24D5,
                            struct.pack("<I", 0xDEADBEEF) + b"\x6b" + key_part, packet)
    out.write(f"udp-server packet={packet.hex()} datagram={datagram.hex()}\n")


if __name__ == "__main__":
    main()
