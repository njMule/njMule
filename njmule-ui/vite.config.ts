import vue from '@vitejs/plugin-vue';
import { createReadStream, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { Plugin } from 'vite';
import { defineConfig } from 'vitest/config';

const build = (path: string) => fileURLToPath(new URL(`./build/${path}`, import.meta.url));

// In development the translations and the flags come from what the build made of the desktop app's
// (./gradlew :njmule-ui:translations :njmule-ui:flags), unless a web interface serves them (NJMULE_WEB).
function builtFiles(): Plugin {
    const roots: Record<string, [string, string]> = {
        '/i18n/': [build('translations/i18n/'), 'application/json'],
        '/flags/': [build('flags/flags/'), 'image/png'],
    };
    return {
        name: 'njmule-built-files',
        configureServer(server) {
            server.middlewares.use((request, response, next) => {
                const url = request.url ?? '';
                const root = Object.entries(roots).find(([prefix]) => url.startsWith(prefix));
                const name = root ? url.substring(root[0].length).split('?')[0]! : '';
                if (!root || !/^[A-Za-z0-9._-]+$/.test(name) || !existsSync(root[1][0] + name)) {
                    next();
                    return;
                }
                response.setHeader('Content-Type', root[1][1]);
                createReadStream(root[1][0] + name).pipe(response);
            });
        },
    };
}

// Relative paths everywhere: the interface works under any path a reverse proxy gives it, and from the desktop shell.
export default defineConfig({
    base: './',
    plugins: [vue(), ...(process.env.NJMULE_WEB ? [] : [builtFiles()])],
    resolve: {
        alias: {
            // Generated by the build: the API's types (openapi.yaml).
            '@generated': build('generated'),
        },
    },
    build: {
        outDir: 'build/dist',
        emptyOutDir: true,
        // The licenses of every bundled package, shipped beside the interface.
        license: { fileName: 'THIRD-PARTY.md' },
        chunkSizeWarningLimit: 2048,
    },
    server: {
        // In development a running njMule answers the API: NJMULE_API, such as the desktop shell's endpoint, whose
        // token comes in VITE_NJMULE_TOKEN, or a web interface (NJMULE_WEB).
        proxy: {
            '/api': {
                target: process.env.NJMULE_API ?? process.env.NJMULE_WEB ?? 'http://127.0.0.1:4711',
                // The engine refuses pages of other origins: the proxy is no page.
                configure: (proxy) => proxy.on('proxyReq', (request) => request.removeHeader('origin')),
            },
            ...(process.env.NJMULE_WEB ? { '/i18n': process.env.NJMULE_WEB, '/flags': process.env.NJMULE_WEB } : {}),
        },
    },
    test: {
        environment: 'happy-dom',
    },
});
